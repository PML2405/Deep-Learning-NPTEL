#!/usr/bin/env python3
"""Scan slides/, transcripts/ and assignments/ and write manifest.js.

Run from anywhere:  python3 tools/build_manifest.py
Filenames must follow:
  slides/       Week NN - Lecture NN - <Title>.pdf
  transcripts/  Week NN - Transcript[ (Part X)].pdf
  assignments/  Week NN - Assignment Solution.pdf
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Short display names per week (edit when new weeks are added).
WEEK_TITLES = {
    1: "History & the Perceptron",
    2: "Sigmoid Neurons & Gradient Descent",
    3: "Feedforward Networks & Backpropagation",
    4: "Optimization Algorithms",
    5: "Linear Algebra for PCA & SVD",
    6: "Autoencoders",
    7: "Regularization",
    8: "Training Deep Networks",
    9: "Word Representations",
    10: "Convolutional Neural Networks",
    11: "Recurrent Networks, LSTMs & GRUs",
    12: "Encoder-Decoder Models & Attention",
}

SLIDE_RE = re.compile(r"^Week (\d+) - Lecture (\d+) - (.+)\.pdf$")
TRANS_RE = re.compile(r"^Week (\d+) - Transcript(?: \((.+)\))?\.pdf$")
ASSIGN_RE = re.compile(r"^Week (\d+) - Assignment Solution\.pdf$")


def entry(folder, path, label, **extra):
    return {
        "label": label,
        "path": f"{folder}/{path.name}",
        "size": path.stat().st_size,
        **extra,
    }


def tags_from_title(title):
    parts = re.split(r",\s*| - ", title)
    return [p.strip() for p in parts if p.strip()]


def main():
    weeks = {}

    def week(n):
        return weeks.setdefault(
            n,
            {
                "week": n,
                "title": WEEK_TITLES.get(n, f"Week {n}"),
                "topics": [],
                "slides": [],
                "transcripts": [],
                "assignments": [],
            },
        )

    for p in sorted((ROOT / "slides").glob("*.pdf")):
        m = SLIDE_RE.match(p.name)
        if not m:
            print(f"skip (unrecognised name): {p.name}")
            continue
        w, lec, title = int(m[1]), int(m[2]), m[3]
        wk = week(w)
        wk["slides"].append(entry("slides", p, f"Lecture {lec}: {title}", lecture=lec))
        for t in tags_from_title(title):
            if t not in wk["topics"]:
                wk["topics"].append(t)

    for p in sorted((ROOT / "transcripts").glob("*.pdf")):
        m = TRANS_RE.match(p.name)
        if not m:
            print(f"skip (unrecognised name): {p.name}")
            continue
        label = f"Transcript ({m[2]})" if m[2] else "Transcript"
        week(int(m[1]))["transcripts"].append(entry("transcripts", p, label))

    for p in sorted((ROOT / "assignments").glob("*.pdf")):
        m = ASSIGN_RE.match(p.name)
        if not m:
            print(f"skip (unrecognised name): {p.name}")
            continue
        week(int(m[1]))["assignments"].append(entry("assignments", p, "Assignment Solution"))

    data = {
        "course": "Deep Learning",
        "provider": "NPTEL",
        "weeks": [weeks[n] for n in sorted(weeks)],
    }
    out = ROOT / "manifest.js"
    out.write_text(
        "// Generated by tools/build_manifest.py - do not edit by hand.\n"
        "window.MANIFEST = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    n_files = sum(len(w[k]) for w in data["weeks"] for k in ("slides", "transcripts", "assignments"))
    print(f"wrote {out.name}: {len(data['weeks'])} weeks, {n_files} files")


if __name__ == "__main__":
    main()
